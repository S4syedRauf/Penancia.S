using Penancia.S.Domain.Rules;

namespace Penancia.S.Domain.Narrative;

public static class TemplateNarrative
{
    public const string FixedLimitations =
        "Semen analysis results exhibit significant biological variation. Results must be interpreted in clinical correlation with reproductive history by a qualified medical professional.";

    // NOTE (2026-11-21 fix): the previous wording asserted "repeat evaluation
    // after 2-4 weeks is recommended per WHO guidelines" with no source cited
    // in the code. That interval is UNVERIFIED against the WHO 6th Edition —
    // do not present it as a WHO recommendation. The clinical lead must confirm
    // the repeat-evaluation interval before any interval is stated here.
    public const string FixedClosing =
        "Clinical correlation is required. [Unverified: a repeat-evaluation interval was previously asserted here (2-4 weeks) without a verified WHO 6th Edition citation; confirm the interval with the clinical lead before stating one.]";

    public static string GenerateSentence(ClinicalFlag flag, EvaluationResult eval)
    {
        return flag.Code switch
        {
            "BELOW_REFERENCE" => GenerateBelowReferenceSentence(flag, eval),
            "ABOVE_REFERENCE" => GenerateAboveReferenceSentence(flag, eval),
            "ALL_NORMAL" => "All examined seminal parameters meet or exceed the WHO 2021 6th Edition lower reference limits.",
            "INCOMPLETE" => $"{flag.FieldId ?? "One or more parameters"} was not available at the time of reporting.",
            "TRACKERS_DISAGREE" => "Two independent analyses of motility differed; the reported value was confirmed by review.",
            "SINGLE_TRACKER" => "A single automated tracking model was utilized; findings verified by manual review.",
            "MANUAL_REVIEW_REQUIRED" => "Midpiece and tail findings require review by a morphologist.",
            "NOT_VALIDATED" => "This report was generated by a system that has not completed clinical validation.",
            "MOTILITY_EXCEEDS_VITALITY" => "Observed total motility exceeds recorded vitality, requiring laboratory confirmation.",
            "CONCENTRATION_MISMATCH" => "Discrepancy observed between video and manual counting chamber concentrations.",
            _ => flag.Detail
        };
    }

    public static string BuildFullNarrative(EvaluationResult eval)
    {
        ArgumentNullException.ThrowIfNull(eval);
        var sentences = new List<string>();

        foreach (var flag in eval.Flags.Where(f => f.Code != "UNVERIFIED"))
        {
            sentences.Add(GenerateSentence(flag, eval));
        }

        if (sentences.Count == 0)
        {
            sentences.Add("All examined seminal parameters meet or exceed the WHO 2021 6th Edition lower reference limits.");
        }

        sentences.Add(FixedClosing);
        return string.Join(" ", sentences);
    }

    private static string GenerateBelowReferenceSentence(ClinicalFlag flag, EvaluationResult eval)
    {
        var row = eval.Rows.FirstOrDefault(r => r.FieldId == flag.FieldId);
        if (row != null && row.Value.HasValue)
        {
            // The reference is parenthesised ("limit (≥ 42 %)") so the sentence
            // never reads as the contradictory "below the limit of ≥ 42 %".
            return $"{row.Label} was {row.DisplayValue} {row.Unit}, below the WHO 2021 lower reference limit ({row.ReferenceText}).";
        }
        return $"{flag.FieldId ?? "Parameter"} was below the WHO 2021 lower reference limit.";
    }

    private static string GenerateAboveReferenceSentence(ClinicalFlag flag, EvaluationResult eval)
    {
        var row = eval.Rows.FirstOrDefault(r => r.FieldId == flag.FieldId);
        if (row != null && row.Value.HasValue)
        {
            return $"{row.Label} was {row.DisplayValue} {row.Unit}, above the WHO 2021 upper reference limit ({row.ReferenceText}).";
        }
        return $"{flag.FieldId ?? "Parameter"} was above the WHO 2021 upper reference limit.";
    }
}
